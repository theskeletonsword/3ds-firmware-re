#!/usr/bin/env python3
"""Write docs/DECOMPILATION_STATUS.md: per binary, how many functions the bulk Ghidra pass decompiled and how many named functions exist. Run any time."""
import csv, glob, os
R = os.path.abspath(os.path.dirname(__file__) + '/../..')
rows = []
for idx in sorted(glob.glob(f'{R}/*/*/*/decompiled*/index.tsv') + glob.glob(f'{R}/*/*/*/*/decompiled*/index.tsv')):
    n = ok = fail = 0
    for r in csv.DictReader(open(idx), delimiter='\t'):
        n += 1; ok += r['status'] in ('ok', 'existing'); fail += r['status'] == 'fail'
    d = os.path.dirname(idx); nm = sum(1 for _ in open(d + '/names.tsv')) if os.path.exists(d + '/names.tsv') else 0
    rows.append((os.path.relpath(d, R), n, ok, fail, nm))
running = [d for d in glob.glob(f'{R}/*/*/*/decompiled*') + glob.glob(f'{R}/*/*/*/*/decompiled*') if os.path.isdir(d) and not os.path.exists(d + '/index.tsv')]
out = ['# Decompilation status (generated by tools/decompile_status.py)\n', 'Bulk pass = headless Ghidra 12.2 (`tools/decompile_all.sh`), C files in `<binary>/decompiled/<addr>.c`.\n',
       '| directory | functions | decompiled | failed | functions pre-named from our tables |', '|---|---:|---:|---:|---:|']
out += [f'| `{d}` | {n} | {ok} | {f} | {nm} |' for d, n, ok, f, nm in rows]
out.append(f'\nBinaries finished: {len(rows)}; in progress / not started (no index.tsv yet): {len(running)}\n')
tot = sum(r[1] for r in rows); out.append(f'Total functions decompiled so far: {sum(r[2] for r in rows)} of {tot} discovered.\n')
open(f'{R}/n3ds/docs/DECOMPILATION_STATUS.md', 'w').write('\n'.join(out)); print(out[-3], out[-1])
