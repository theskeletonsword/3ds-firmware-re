#!/usr/bin/env python3
"""Recover IPC command tables from the bulk-decompiled C (decompiled/*.c).

A dispatcher is a function that reads the command buffer from the TLS pointer (`coproc_movefrom_User_R_Thread_and_Process_ID`) and does
`switch(*cmdbuf >> 0x10)` (command id = header >> 16, 3dbrew IPC format) or compares the header against constants. For every `case N:` it records the first
function called in the case body, the reply-header literal stored back (`*cmdbuf = 0x...` / `puVar[0] = DAT/const`) and the parameter count implied by cmdbuf[1..] reads.
usage: extract_ipc_from_decomp.py [root ...]   (default: n3ds + o3ds decrypted_binaries/decrypted_titles)   -> n3ds/symbols/ipc/IPC_COMMANDS_FROM_DECOMPILATION.csv
"""
import csv, glob, os, re, sys
R = os.path.abspath(os.path.dirname(__file__) + '/../..')
rows = []
sw = re.compile(r'switch\((?:\*?\(?(?:uint|int|undefined4|ushort)?\s*\*?\)?)?[\w\s\*\(\)\+]*?>>\s*(?:0x10|16)\)\s*\{')
for cdir in sorted(glob.glob(f'{R}/*/*/*/decompiled') + glob.glob(f'{R}/*/*/*/*/decompiled')):
    binary = os.path.relpath(os.path.dirname(cdir), R)
    for cf in sorted(glob.glob(cdir + '/*.c')):
        t = open(cf, errors='replace').read()
        if 'coproc_movefrom_User_R_Thread_and_Process_ID' not in t or '>> 0x10' not in t: continue
        m = re.search(r'switch\([^\n]*>>\s*0x10\)\s*\{', t)
        if not m: continue
        body = t[m.end():]
        fname = re.search(r'^// (\S+) @ (0x[0-9a-f]+)', t, re.M)
        parts = re.split(r'\n\s*case\s+(0x[0-9a-fA-F]+|\d+):', '\n' + body)
        n = 0
        for i in range(1, len(parts) - 1, 2):
            cid = int(parts[i], 0); blk = parts[i + 1].split('\n  default:')[0]
            call = re.search(r'\b((?:FUN|[A-Za-z_][A-Za-z0-9_]*)_?[0-9a-f]{6,8}|[A-Za-z_][A-Za-z0-9_]{5,})\s*\(', blk)
            reply = re.search(r'\*\s*\w+\s*=\s*(0x[0-9a-fA-F]+|DAT_[0-9a-f]+)\s*;', blk)
            nargs = len(set(re.findall(r'\+\s*(0x[0-9a-f]+|\d+)\)', blk)) )
            rows.append([binary, fname.group(2) if fname else '', fname.group(1) if fname else '', f'0x{cid:04X}', call.group(1) if call else '', reply.group(1) if reply else '', nargs])
            n += 1
os.makedirs(R + '/n3ds/symbols/ipc', exist_ok=True)
with open(R + '/n3ds/symbols/ipc/IPC_COMMANDS_FROM_DECOMPILATION.csv', 'w', newline='') as f:
    w = csv.writer(f); w.writerow(['binary', 'dispatcher_ea', 'dispatcher_name', 'cmd_id', 'first_call_in_case', 'reply_header_or_data_ref', 'cmdbuf_words_touched']); w.writerows(rows)
print(len(rows), 'case rows from', len({(r[0], r[1]) for r in rows}), 'dispatchers in', len({r[0] for r in rows}), 'binaries')
# ---- markdown summary
import collections as _c
by = _c.defaultdict(list)
for r in rows: by[(r[0], r[1], r[2])].append(r)
md = ['# IPC dispatchers recovered from decompiled C (auto-generated by tools/extract_ipc_from_decomp.py)\n',
      'A dispatcher = function reading the TLS command buffer and doing `switch(cmdbuf[0] >> 16)`. Full per-case rows (first call per case, reply header/data reference): `symbols/ipc/IPC_COMMANDS_FROM_DECOMPILATION.csv`.',
      'Cross-check with earlier hand-made analysis: gsp::Gpu 31 commands, hid 24, mcu::RTC 92, matching `o3ds/SYSMODULES_WIFI_DRIVERS_MANUAL.md`.\n',
      '| binary | dispatcher | cases | command ids | distinct handlers |', '|---|---|---:|---|---:|']
for (b, ea, nm), rs in sorted(by.items()):
    ids = sorted(int(x[3], 16) for x in rs); span = f'0x{ids[0]:02X}..0x{ids[-1]:02X}' if ids else ''
    md.append(f"| `{os.path.basename(b)}` | `{nm}` @ {ea} | {len(rs)} | {span} | {len({x[4] for x in rs})} |")
os.makedirs(R + '/n3ds/docs/decompiled_notes', exist_ok=True)
open(R + '/n3ds/docs/decompiled_notes/IPC_TABLES.md', 'w').write('\n'.join(md) + '\n')
